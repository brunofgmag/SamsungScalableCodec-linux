"""Write the SSC mode tables (band layout, allocation) read from the emulated encoder as a C header.

    ssc_gen_tables.py LIB.so OUT.h
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ssc_oracle import Oracle  # noqa: E402


def main():
    lib, out = sys.argv[1], sys.argv[2]
    o = Oracle(lib)
    err = o.alloc(size=4)
    st = o.call("ssc_encoder_create", 44100, 2, 16, err)
    mode = struct.unpack("<Q", o.read(st, 8))[0]
    raw = o.read(mode, 0x60)
    Fs, overlap, nb, eff = struct.unpack("<4i", raw[:16])
    eb_ptr = struct.unpack("<Q", raw[16:24])[0]
    nbShort, shortSz, nbAlloc = struct.unpack("<3i", raw[24:36])
    alloc_ptr = struct.unpack("<Q", raw[40:48])[0]
    eb = struct.unpack("<%dh" % (nb + 1), o.read(eb_ptr, 2 * (nb + 1)))
    maxLM = nbShort.bit_length() - 1
    index_p = struct.unpack("<Q", o.read(mode + 0x68, 8))[0]       # PulseCache.index (the 'bits' table is identical to Opus')
    cindex = struct.unpack("<%dh" % ((maxLM + 2) * nb), o.read(index_p, 2 * (maxLM + 2) * nb))
    al = o.read(alloc_ptr, nbAlloc * nb)
    alloc_b_ptr = struct.unpack("<Q", o.read(mode + 0x30, 8))[0]   # second allocation table, selected by a flag inside ssc_compute_allocation
    al_b = o.read(alloc_b_ptr, nbAlloc * nb)
    with open(out, "w") as f:
        f.write("/* SSC mode tables, read from the Samsung encoder (generated by tools/ssc_gen_tables.py) */\n")
        f.write("#define SSC_FS %d\n#define SSC_FRAME_SIZE %d\n#define SSC_OVERLAP %d\n" % (Fs, nbShort * shortSz, overlap))
        f.write("#define SSC_NB_EBANDS %d\n#define SSC_NB_ALLOC_VECTORS %d\n" % (nb, nbAlloc))
        f.write("static const short ssc_ebands[%d] = {%s};\n" % (nb + 1, ", ".join(map(str, eb))))
        f.write("static const unsigned char ssc_alloc[%d] = {\n" % (nbAlloc * nb))
        for i in range(nbAlloc):
            f.write("    %s,\n" % ", ".join(str(x) for x in al[i * nb:(i + 1) * nb]))
        f.write("};\n")
        f.write("static const unsigned char ssc_alloc_b[%d] = {\n" % (nbAlloc * nb))
        for i in range(nbAlloc):
            f.write("    %s,\n" % ", ".join(str(x) for x in al_b[i * nb:(i + 1) * nb]))
        f.write("};\n")
        f.write("/* PulseCache.index: Samsung's differs from Opus' for band 20 (it shares the row of the 18-wide band 21) */\n")
        f.write("static const short ssc_cache_index[%d] = {%s};\n" % (len(cindex), ", ".join(map(str, cindex))))
    print("wrote", out)


if __name__ == "__main__":
    main()
