"""Write the SSC mode tables (band layout, allocation, pulse-cache index) read from the emulated encoder as a C header.

The library holds two CELT modes: the one for 44.1/48 kHz ("ssc_" tables) and the one it selects for 96 kHz
("ssc96_" tables, the UHQ mode).

    ssc_gen_tables.py LIB.so OUT.h
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ssc_oracle import Oracle  # noqa: E402


def read_mode(lib, fs):
    o = Oracle(lib)
    err = o.alloc(size=4)
    st = o.call("ssc_encoder_create", fs, 2, 16, err)
    mode = struct.unpack("<Q", o.read(st, 8))[0]
    raw = o.read(mode, 0x80)
    m = {}
    m["fs"], m["overlap"], m["nb"], m["eff"] = struct.unpack("<4i", raw[:16])
    eb_ptr = struct.unpack("<Q", raw[16:24])[0]
    nb_short, short_sz, nb_alloc = struct.unpack("<3i", raw[24:36])
    m["frame"], m["nb_alloc"] = nb_short * short_sz, nb_alloc
    max_lm = nb_short.bit_length() - 1
    m["ebands"] = struct.unpack("<%dh" % (m["nb"] + 1), o.read(eb_ptr, 2 * (m["nb"] + 1)))
    alloc_ptr = struct.unpack("<Q", raw[40:48])[0]                      # table "A"
    alloc_b_ptr = struct.unpack("<Q", o.read(mode + 0x30, 8))[0]       # table "B", selected by a flag inside ssc_compute_allocation
    m["alloc"] = o.read(alloc_ptr, nb_alloc * m["nb"])
    m["alloc_b"] = o.read(alloc_b_ptr, nb_alloc * m["nb"])
    index_p = struct.unpack("<Q", raw[0x68:0x70])[0]                   # PulseCache.index (the 'bits' table is identical to Opus')
    m["cache_index"] = struct.unpack("<%dh" % ((max_lm + 2) * m["nb"]), o.read(index_p, 2 * (max_lm + 2) * m["nb"]))
    return m


def write_mode(f, p, m, comment=""):
    nb, na = m["nb"], m["nb_alloc"]
    f.write("%s\n" % comment)
    f.write("#define %sFS %d\n" % (p.upper(), m["fs"]))
    f.write("static const short %sebands[%d] = {%s};\n" % (p, nb + 1, ", ".join(map(str, m["ebands"]))))
    for name, key in (("", "alloc"), ("_b", "alloc_b")):
        f.write("static const unsigned char %salloc%s[%d] = {\n" % (p, name, na * nb))
        for i in range(na):
            f.write("    %s,\n" % ", ".join(str(x) for x in m[key][i * nb:(i + 1) * nb]))
        f.write("};\n")
    f.write("static const short %scache_index[%d] = {%s};\n" % (p, len(m["cache_index"]), ", ".join(map(str, m["cache_index"]))))


def main():
    lib, out = sys.argv[1], sys.argv[2]
    m0, m1 = read_mode(lib, 44100), read_mode(lib, 96000)
    for key in ("overlap", "nb", "eff", "frame", "nb_alloc"):
        assert m0[key] == m1[key], key
    with open(out, "w") as f:
        f.write("/* SSC mode tables, read from the Samsung encoder (generated by tools/ssc_gen_tables.py) */\n")
        f.write("#define SSC_FRAME_SIZE %d\n#define SSC_OVERLAP %d\n" % (m0["frame"], m0["overlap"]))
        f.write("#define SSC_NB_EBANDS %d\n#define SSC_NB_ALLOC_VECTORS %d\n" % (m0["nb"], m0["nb_alloc"]))
        write_mode(f, "ssc_", m0, "/* 44.1 / 48 kHz mode. PulseCache.index: Samsung's differs from Opus' for band 20 (it shares the row of the 18-wide band 21) */")
        write_mode(f, "ssc96_", m1, "/* 96 kHz (UHQ) mode */")
    print("wrote", out)


if __name__ == "__main__":
    main()
